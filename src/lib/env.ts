import type { DataMode } from '@/types';

/**
 * 환경 설정 한 곳 모음.
 *
 * DATA_MODE=mock  → lib/api/client.ts 가 실제 fetch 대신 src/mocks/raw 를 반환
 * DATA_MODE=live  → 공공데이터포털 실 API 호출
 *
 * ── 판정은 서버 런타임 값으로만 한다 ────────────────────
 * 예전에는 NEXT_PUBLIC_DATA_MODE 가 'live' 인지를 함께 봤다. 그게 사고를 냈다.
 *
 * Next 는 NEXT_PUBLIC_* 을 **빌드 시점에 문자열로 박아 넣는다**. 그래서 그 변수가
 * 없던 시점에 만들어진 빌드는 조건이 통째로 false 로 접혀 버리고, 나중에 런타임
 * 환경변수를 아무리 채워도 영원히 mock 으로 돈다. 실제로 배포본이 그 상태였다 —
 * /api/health 는 키가 다 있다고 하는데 화면에는 '예시 데이터' 배지가 떴다.
 * (빌드 산출물에서 확인: NEXT_PUBLIC_DATA_MODE 는 흔적도 없이 사라져 있었다)
 *
 * 지금은 **서버에서만 읽히는 키의 존재 여부**로 정한다. 이 값들은 빌드에
 * 박히지 않고 매 요청 런타임에 읽히므로, 키를 넣으면 재배포 없이도 즉시 반영된다.
 * 판정 기준과 실제로 호출에 쓰는 값이 같아져서 둘이 어긋날 수도 없다.
 *
 * 시연용으로 일부러 예시 데이터를 쓰고 싶으면 SOOMGIL_FORCE_MOCK=1 을 준다.
 * (예전 표기 NEXT_PUBLIC_DATA_MODE=mock 도 계속 받아 준다)
 */
const FORCE_MOCK =
  process.env.SOOMGIL_FORCE_MOCK === '1' ||
  process.env.NEXT_PUBLIC_DATA_MODE === 'mock';

export const DATA_MODE: DataMode =
  !FORCE_MOCK && (process.env.DATA_GO_KR_SERVICE_KEY || process.env.KMA_APIHUB_KEY)
    ? 'live'
    : 'mock';

/**
 * 공공데이터포털(data.go.kr) 일반 인증키 (Decoding). 서버에서만 읽는다.
 *
 * 계정 하나로 신청한 서비스 전부에 같은 키를 쓴다.
 * 여기서는 에어코리아 대기오염정보 · 꽃가루농도위험지수 · 생활기상지수에 해당한다.
 */
export const SERVICE_KEY = process.env.DATA_GO_KR_SERVICE_KEY ?? '';

/**
 * 기상청 API허브(apihub.kma.go.kr) 인증키.
 *
 * ⚠ data.go.kr 키와 다른 키다.
 * 단기예보·초단기실황은 data.go.kr이 아니라 API허브에서 받는다. 파라미터 이름도
 * serviceKey 가 아니라 authKey 이고 호스트도 다르다. 확인해 본 결과 같은 오퍼레이션을
 * data.go.kr 쪽으로 부르면 SERVICE_KEY_IS_NOT_REGISTERED 가 돌아온다.
 */
export const KMA_APIHUB_KEY = process.env.KMA_APIHUB_KEY ?? '';

/**
 * TMAP 앱키 (SK Open API).
 *
 * 공공데이터포털과는 완전히 다른 사업자라 인증키도 따로 발급받는다.
 * 이 값이 있으면 경로 안내가 실제 도로 기반(TMAP 보행자 경로)으로 동작하고,
 * 없으면 격자 A*로 자동으로 떨어진다. 코드 수정은 필요 없다.
 *
 * NEXT_PUBLIC_ 접두사를 쓰지 않는다 — 앱키가 브라우저에 노출되면
 * 다른 사이트에서 남용해 우리 호출 한도를 소진시킬 수 있다.
 */
export const TMAP_APP_KEY = process.env.TMAP_APP_KEY ?? '';

/**
 * 서버 캐시 TTL (초).
 *
 * ── 호출 예산 계산 ──────────────────────────────────────────
 * 스냅샷 1회를 만드는 데 필요한 호출 수 (봄 기준, 격자 중복 제거 후)
 *   꽃가루  5개 구 × 2종(소나무·참나무) = 10
 *   대기정체 5개 구                      =  5
 *   단기예보 중복 없는 격자 4개          =  4   ← 인접 구가 같은 격자를 공유
 *   기상특보                             =  1
 *   에어코리아 시도별 실시간(1회로 전 측정소) =  1
 *
 * 전부 20분 캐시로 두면 기상청만 하루 1,440회라 개발계정 한도(보통 일 1,000회)를 넘긴다.
 * 그래서 "데이터가 실제로 갱신되는 주기"에 맞춰 따로 잡는다.
 *
 *   꽃가루·대기정체 : 하루 4회(06/12/18/24시) 발표 → 3시간   → 8회/일 × 15 = 120회/일
 *   단기예보        : 3시간 간격 발표            → 1시간   → 24회/일 ×  4 =  96회/일
 *   기상특보        : 발효·해제가 수시           → 10분    → 144회/일 ×  1 = 144회/일
 *   ─────────────────────────────────── 기상청 합계 약 360회/일 (한도 내)
 *
 *   에어코리아      : 1시간 단위 갱신, 개발계정 일 500회 한도 → 20분 → 72회/일 (한도 내)
 *
 * 발표 주기보다 짧게 캐시해도 같은 값을 다시 받을 뿐이라 신선도 손해가 없다.
 * ────────────────────────────────────────────────────────
 */
export const CACHE_TTL = {
  /** 꽃가루농도위험지수 — 하루 4회 발표 */
  pollen: 3 * 60 * 60,
  /** 대기정체지수 — 하루 4회 발표 */
  stagnation: 3 * 60 * 60,
  /** 단기예보 — 3시간 간격 발표 */
  forecast: 60 * 60,
  /** 기상특보 — 발효·해제가 빨라 짧게 */
  warning: 10 * 60,
  /** 에어코리아 실시간 — 일 500회 한도 고려 */
  airkorea: 20 * 60,
  /** 에어코리아 예보통보 — 하루 4회 발표 */
  airkoreaForecast: 3 * 60 * 60,
  /**
   * TMAP 보행자 경로 — 하루.
   *
   * 도로망은 거의 바뀌지 않으므로 같은 출발/도착 쌍이면 길게 캐시해도 된다.
   * 위험도는 이 경로 위에서 매 요청 새로 계산하므로 신선도 손해가 없고,
   * 시연 중 같은 경로를 반복 조회할 때 호출 한도를 아낄 수 있다.
   */
  tmapRoute: 24 * 60 * 60,
  /**
   * TMAP 장소검색 — 1시간.
   *
   * 같은 검색어를 반복해서 치는 일이 잦고(자동완성은 글자를 지웠다 다시 치면
   * 같은 요청이 또 나간다) 장소 정보 자체는 거의 바뀌지 않는다.
   */
  tmapPoi: 60 * 60,
} as const;

