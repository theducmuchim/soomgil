import type { DataMode } from '@/types';

/**
 * 환경 설정 한 곳 모음.
 *
 * DATA_MODE=mock  → lib/api/client.ts 가 실제 fetch 대신 src/mocks/raw 를 반환
 * DATA_MODE=live  → 공공데이터포털 실 API 호출
 *
 * 키가 없으면 무조건 mock 으로 떨어진다(시연 중 사고 방지).
 */
export const DATA_MODE: DataMode =
  process.env.NEXT_PUBLIC_DATA_MODE === 'live' && process.env.DATA_GO_KR_SERVICE_KEY
    ? 'live'
    : 'mock';

/** 공공데이터포털 일반 인증키 (Decoding). 서버에서만 읽는다. */
export const SERVICE_KEY = process.env.DATA_GO_KR_SERVICE_KEY ?? '';

/**
 * 서버 캐시 TTL (초).
 *
 * ── 호출 예산 계산 ──────────────────────────────────────────
 * 스냅샷 1회를 만드는 데 필요한 호출 수 (봄 기준, 격자 중복 제거 후)
 *   꽃가루  5개 구 × 2종(소나무·참나무) = 10
 *   대기정체 5개 구                      =  5
 *   단기예보 중복 없는 격자 4개          =  4   ← 인접 구가 같은 격자를 공유
 *   기상특보                             =  1
 *   에어코리아 시도별 실시간(1회로 전 측정소) =  1
 *
 * 전부 20분 캐시로 두면 기상청만 하루 1,440회라 개발계정 한도(보통 일 1,000회)를 넘긴다.
 * 그래서 "데이터가 실제로 갱신되는 주기"에 맞춰 따로 잡는다.
 *
 *   꽃가루·대기정체 : 하루 4회(06/12/18/24시) 발표 → 3시간   → 8회/일 × 15 = 120회/일
 *   단기예보        : 3시간 간격 발표            → 1시간   → 24회/일 ×  4 =  96회/일
 *   기상특보        : 발효·해제가 수시           → 10분    → 144회/일 ×  1 = 144회/일
 *   ─────────────────────────────────── 기상청 합계 약 360회/일 (한도 내)
 *
 *   에어코리아      : 1시간 단위 갱신, 개발계정 일 500회 한도 → 20분 → 72회/일 (한도 내)
 *
 * 발표 주기보다 짧게 캐시해도 같은 값을 다시 받을 뿐이라 신선도 손해가 없다.
 * ────────────────────────────────────────────────────────
 */
export const CACHE_TTL = {
  /** 꽃가루농도위험지수 — 하루 4회 발표 */
  pollen: 3 * 60 * 60,
  /** 대기정체지수 — 하루 4회 발표 */
  stagnation: 3 * 60 * 60,
  /** 단기예보 — 3시간 간격 발표 */
  forecast: 60 * 60,
  /** 기상특보 — 발효·해제가 빨라 짧게 */
  warning: 10 * 60,
  /** 에어코리아 실시간 — 일 500회 한도 고려 */
  airkorea: 20 * 60,
  /** 에어코리아 예보통보 — 하루 4회 발표 */
  airkoreaForecast: 3 * 60 * 60,
} as const;

/** 시연용: 계절 강제 전환 (?season=winter). mock 모드에서만 동작. */
export const ALLOW_SEASON_OVERRIDE = DATA_MODE === 'mock';
